#!/usr/bin/env node
/**
 * gdd-to-tests.mjs — generates structural replay specs from GDD §15 acceptance lines (GDD-005).
 * Owner: qa-engineer. Replaced a declared P0-002 stub that exited 1 by design (I5/B7).
 *
 * The generated specs are DRIFT CHECKS, not behavioral proofs: they fail if a GDD acceptance line changes
 * without regeneration. Behavioral evidence stays in docs/state/evidence/ and the harness logs.
 *
 *   node scripts/gdd-to-tests.mjs --generate   write the specs
 *   node scripts/gdd-to-tests.mjs --check      fail if any spec is missing or stale
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';

const MODULES = 'docs/design/gdd';
const OUT = 'tests/replay/gdd';
const MARKER = 'GENERATED by scripts/gdd-to-tests.mjs';
const mode = process.argv.includes('--check') ? 'check' : 'generate';

if (!existsSync(MODULES)) {
  console.error('NOT READABLE — GDD module directory missing. Fail closed.');
  process.exit(2);
}

function expectedSpecs() {
  const specs = new Map();
  let skipped = 0;
  for (const file of readdirSync(MODULES).filter((name) => name.endsWith('.md')).sort()) {
    const id = file.slice(0, -3);
    let text;
    try { text = readFileSync(`${MODULES}/${file}`, 'utf8'); }
    catch (error) { console.error(`NOT READABLE ${file}: ${error.message}`); process.exit(2); }
    const status = /\| status \| (STUB|DRAFT|SIGNED) \|/.exec(text)?.[1];
    if (!status || status === 'STUB') { skipped++; continue; }
    const section = text.split('## 15. Acceptance tests')[1]?.split('\n## ')[0] ?? '';
    const lines = section.split('\n')
      .filter((line) => line.startsWith('- GIVEN'))
      .map((line) => line.replace(/^-\s*/, '').trim())
      .filter((line) => line.length > 0);
    if (lines.length === 0) {
      console.error(`NOT MEASURABLE ${id} is ${status} but §15 has no GIVEN line. Fail closed.`);
      process.exit(2);
    }
    specs.set(id, generate(id, lines));
  }
  return { specs, skipped };
}

function generate(id, lines) {
  return `/**
 * ${MARKER} — structural contract check, NOT behavioral proof.
 * Source: docs/design/gdd/${id}.md §15. Behavioral evidence: docs/state/evidence/.
 * Do not edit by hand; run \`node scripts/gdd-to-tests.mjs --generate\`.
 */
import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';

const SOURCE = 'docs/design/gdd/${id}.md';
const ACCEPTANCE = ${JSON.stringify(lines, null, 2)};

describe('${id} GDD acceptance (structural)', () => {
  const text = readFileSync(SOURCE, 'utf8');
  it('declares acceptance lines in the source module', () => {
    expect(ACCEPTANCE.length).toBeGreaterThan(0);
  });
  for (const [index, line] of ACCEPTANCE.entries()) {
    it(\`A\${index + 1}: \${line.slice(0, 64)}\`, () => {
      expect(text).toContain(line);
      expect(line.startsWith('GIVEN')).toBe(true);
    });
  }
});
`;
}

const { specs, skipped } = expectedSpecs();
if (specs.size === 0) {
  console.error('NOT MEASURABLE — no DRAFT/SIGNED module has acceptance lines. Fail closed.');
  process.exit(2);
}

if (mode === 'generate') {
  mkdirSync(OUT, { recursive: true });
  for (const [id, body] of specs) writeFileSync(`${OUT}/${id}.spec.ts`, body, 'utf8');
  console.log(`gdd-to-tests — generated ${specs.size} specs in ${OUT}/ (${skipped} STUB modules skipped)`);
  console.log('structural drift checks only — behavioral proof stays in docs/state/evidence/');
  process.exit(0);
}

const problems = [];
for (const [id, body] of specs) {
  const path = `${OUT}/${id}.spec.ts`;
  if (!existsSync(path)) { problems.push(`${id}: missing ${path}`); continue; }
  if (readFileSync(path, 'utf8') !== body) problems.push(`${id}: stale (GDD §15 changed — run --generate)`);
}
if (existsSync(OUT)) {
  for (const file of readdirSync(OUT).filter((name) => name.endsWith('.spec.ts'))) {
    const id = file.slice(0, -8);
    if (specs.has(id)) continue;
    const content = readFileSync(`${OUT}/${file}`, 'utf8');
    if (content.includes(MARKER)) problems.push(`${id}: generated spec has no DRAFT/SIGNED source module`);
  }
}
if (problems.length) {
  console.error(`gdd-to-tests --check — FAIL (${problems.length})`);
  for (const problem of problems) console.error(`  - ${problem}`);
  process.exit(1);
}
console.log(`gdd-to-tests --check — PASS — ${specs.size} specs match their GDD source (${skipped} STUB skipped)`);
